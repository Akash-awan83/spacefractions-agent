def write(root, files: dict):
    for rel, content in files.items():
        p = root / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(content, encoding="utf-8")


def script_writing(files: dict, final_text: str = "Done.") -> list:
    """Fake-model messages that write the files, then finish."""
    calls = [{"id": f"w{i}", "type": "function",
              "function": {"name": "write_file", "arguments": json.dumps({"path": p, "content": c})}}
             for i, (p, c) in enumerate(files.items())]
    return [{"role": "assistant", "content": None, "reasoning_content": "write", "tool_calls": calls},
            {"role": "assistant", "content": final_text, "reasoning_content": "finish"}]
