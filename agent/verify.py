"""Step 3: the verifier - deterministic quality gates for the generated project.

The model cannot simply declare "done": when it tries to finish, the agent loop runs
these checks and sends any blocking issue back to the model (a "stop hook").

Each issue is labelled with a category from the taxonomy of
  Gao, Tahir, Liang, Susnjak, Khomh, "A Survey of Bugs in AI-Generated Code" (arXiv:2512.05239)
  -> Functional, Syntax, Hallucination, Code style & standards, System, Reliability
plus three categories this agent adds for project-level generation:
  -> Security, Design conformance (cf. "Beyond Functional Correctness: Design Issues in AI
     IDE-Generated Large-Scale Projects"), Traceability & documentation.

Every verification round is recorded; at the end .agent/bug_report.json lists which
issues appeared, in which round, and whether the agent fixed them.
"""
from __future__ import annotations

import ast
import csv
import io
import json
import re
import sys
from dataclasses import asdict, dataclass, field
from pathlib import Path

# ---- the contract shared with the system prompt (prompts.py imports these) ----------
ROOT_PACKAGE = "spacefractions"
EXPECTED_PACKAGES = ("game", "question", "user", "admin", "storage", "ui")
DOMAIN_PACKAGES = ("game", "question", "user", "admin", "storage")   # must not import ui
REQUIRED_FILES = ("main.py", "README.md", "DECISIONS.md", "traceability_matrix.csv",
                  "requirements.txt", "Dockerfile", "AGENTS.md", "tests/__init__.py")
# The evaluation requires a DESKTOP game: the UI must be Tkinter and nothing may serve web pages.
WEB_MODULES = {"flask", "django", "fastapi", "starlette", "streamlit", "gradio", "bottle", "tornado",
               "aiohttp", "http.server", "wsgiref", "socketserver", "cherrypy", "pyramid", "sanic"}
HEADER_MARK = "Generated by SpaceFractions Code Agent"
MIN_TESTS = 8
FORBIDDEN_CALLS = {"eval", "exec", "os.system", "os.popen", "subprocess.run", "subprocess.call",
                   "subprocess.Popen", "subprocess.check_output", "pickle.loads", "__import__"}
SQL_METHODS = {"execute", "executemany"}

STDLIB = set(getattr(sys, "stdlib_module_names", ())) | {"__future__"}
SKIP_DIRS = {".agent", "__pycache__", ".git", ".venv", "venv", "build", "dist"}


@dataclass
class Issue:
    check: str
    category: str
    message: str
    file: str = ""
    line: int = 0
    blocking: bool = True

    @property
    def signature(self) -> str:
        return f"{self.check}|{self.file}|{re.sub(r'[0-9]+', '#', self.message)[:120]}"


@dataclass
class Report:
    round: int
    issues: list = field(default_factory=list)
    tests_run: int = 0
    tests_ok: bool = False

    @property
    def blocking(self) -> list:
        return [i for i in self.issues if i.blocking]

    @property
    def passed(self) -> bool:
        return not self.blocking

    def format(self, limit: int = 30) -> str:
        if self.passed:
            warn = len(self.issues)
            return (f"VERIFICATION PASSED (round {self.round}): {self.tests_run} tests green"
                    + (f", {warn} non-blocking warning(s):\n" + _lines(self.issues, limit) if warn else "."))
        head = (f"VERIFICATION FAILED (round {self.round}): {len(self.blocking)} blocking issue(s), "
                f"{len(self.issues) - len(self.blocking)} warning(s). Fix the blocking ones:")
        ordered = self.blocking + [i for i in self.issues if not i.blocking]
        return head + "\n" + _lines(ordered, limit)


def _lines(issues: list, limit: int) -> str:
    out = []
    for i in issues[:limit]:
        loc = f"{i.file}:{i.line}" if i.line else (i.file or "-")
        out.append(f"- [{i.category}]{'' if i.blocking else ' (warning)'} {loc}: {i.message}")
    if len(issues) > limit:
        out.append(f"... and {len(issues) - limit} more")
    return "\n".join(out)


# ---- test-failure classification (survey taxonomy) ------------------------------------------
def classify_test_problem(trace: str) -> str:
    if re.search(r"\b(ModuleNotFoundError|ImportError)\b|has no attribute|cannot import name", trace):
        return "Hallucination"
    if "SyntaxError" in trace or "IndentationError" in trace:
        return "Syntax"
    if re.search(r"\b(RecursionError|MemoryError)\b", trace):
        return "System"
    if re.search(r"\b(sqlite3\.\w+Error|OSError|PermissionError|TimeoutError)\b", trace):
        return "Reliability"
    return "Functional"


# ---- module index for import checking --------------------------------------------------------
def _module_name(rel: Path) -> str:
    parts = list(rel.with_suffix("").parts)
    if parts[-1] == "__init__":
        parts = parts[:-1]
    return ".".join(parts)


def _defined_names(tree: ast.Module) -> tuple[set, bool]:
    names, star = set(), False

    def scan(body):
        nonlocal star
        for node in body:
            if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
                names.add(node.name)
            elif isinstance(node, ast.Assign):
                for t in node.targets:
                    for n in ast.walk(t):
                        if isinstance(n, ast.Name):
                            names.add(n.id)
            elif isinstance(node, (ast.AnnAssign, ast.AugAssign)) and isinstance(node.target, ast.Name):
                names.add(node.target.id)
            elif isinstance(node, ast.Import):
                for a in node.names:
                    names.add(a.asname or a.name.split(".")[0])
            elif isinstance(node, ast.ImportFrom):
                for a in node.names:
                    if a.name == "*":
                        star = True
                    names.add(a.asname or a.name)
            elif isinstance(node, (ast.If, ast.Try, ast.With)):
                scan(node.body)
                for h in getattr(node, "handlers", []):
                    scan(h.body)
                scan(getattr(node, "orelse", []))
                scan(getattr(node, "finalbody", []))

    scan(tree.body)
    return names, star


def _guarded_by_import_error(node: ast.AST, parents: dict) -> bool:
    p = parents.get(node)
    while p is not None:
        if isinstance(p, ast.Try):
            for h in p.handlers:
                t = h.type
                types = t.elts if isinstance(t, ast.Tuple) else [t]
                if any(isinstance(x, ast.Name) and x.id in ("ImportError", "ModuleNotFoundError") for x in types):
                    return True
        p = parents.get(p)
    return False


def _call_name(func: ast.AST) -> str:
    if isinstance(func, ast.Name):
        return func.id
    if isinstance(func, ast.Attribute):
        base = _call_name(func.value)
        return f"{base}.{func.attr}" if base else func.attr
    return ""


# ---- the verifier ----------------------------------------------------------------------------
class Verifier:
    def __init__(self, root: Path, arch: dict, run_tests=None, log_dir: Path | None = None):
        """run_tests: callable returning the runner's raw result dict (ToolBox.run_tests_raw)."""
        self.root = Path(root).resolve()
        self.arch = arch
        self.run_tests = run_tests
        self.log_dir = Path(log_dir) if log_dir else self.root / ".agent"
        self.history: list[Report] = []

    # public ------------------------------------------------------------------------------
    def __call__(self, stage: str = "check") -> Report:
        rep = Report(round=len(self.history) + 1)
        files = self._py_files()
        trees = self._parse_all(files, rep)
        self._check_structure(rep)
        index = {_module_name(f.relative_to(self.root)): f for f in files}
        self._imports_seen: dict[str, set] = {}
        for f, tree in trees.items():
            self._check_file(f, tree, index, trees, rep)
        self._check_desktop_ui(rep)
        self._check_docs(rep)
        self._check_tests(rep)
        self.history.append(rep)
        self.write_bug_report()
        return rep

    # helpers ----------------------------------------------------------------------------
    def _rel(self, p: Path) -> str:
        return p.relative_to(self.root).as_posix()

    def _py_files(self) -> list[Path]:
        out = []
        for p in sorted(self.root.rglob("*.py")):
            if not any(part in SKIP_DIRS for part in p.relative_to(self.root).parts):
                out.append(p)
        return out

    def _parse_all(self, files: list[Path], rep: Report) -> dict:
        trees = {}
        for f in files:
            try:
                src = f.read_text(encoding="utf-8")
                trees[f] = ast.parse(src, filename=str(f))
            except SyntaxError as e:
                rep.issues.append(Issue("syntax", "Syntax", f"{e.msg}", self._rel(f), e.lineno or 0))
            except (UnicodeDecodeError, ValueError) as e:
                rep.issues.append(Issue("syntax", "Syntax", f"cannot read: {e}", self._rel(f)))
        return trees

    def _check_structure(self, rep: Report):
        for rel in REQUIRED_FILES:
            if not (self.root / rel).is_file():
                rep.issues.append(Issue("deliverables", "Traceability & documentation",
                                        f"required file missing: {rel}", rel))
        for pkg in EXPECTED_PACKAGES:
            if not (self.root / ROOT_PACKAGE / pkg / "__init__.py").is_file():
                rep.issues.append(Issue("architecture", "Design conformance",
                                        f"component package missing: {ROOT_PACKAGE}/{pkg}/__init__.py "
                                        f"(the component diagram requires it)", f"{ROOT_PACKAGE}/{pkg}"))

    def _check_file(self, f: Path, tree: ast.Module, index: dict, trees: dict, rep: Report):
        rel = self._rel(f)
        src = f.read_text(encoding="utf-8")
        modname = _module_name(f.relative_to(self.root))
        is_pkg = f.name == "__init__.py"

        # header (self-declaration of AI-generated code)
        if src.strip() and HEADER_MARK not in "\n".join(src.splitlines()[:5]):
            rep.issues.append(Issue("header", "Code style & standards",
                                    f"missing AI-generated header ('# {HEADER_MARK} ...') in the first lines", rel, 1))

        parents = {child: node for node in ast.walk(tree) for child in ast.iter_child_nodes(node)}
        in_domain = next((p for p in DOMAIN_PACKAGES if modname.startswith(f"{ROOT_PACKAGE}.{p}")), None)

        for node in ast.walk(tree):
            # imports: hallucinated modules/names, stdlib-only rule, layering
            if isinstance(node, (ast.Import, ast.ImportFrom)):
                if _guarded_by_import_error(node, parents):
                    continue
                targets = []
                if isinstance(node, ast.Import):
                    targets = [(a.name, None) for a in node.names]
                else:
                    base = node.module or ""
                    if node.level:
                        pkg_parts = modname.split(".") if is_pkg else modname.split(".")[:-1]
                        up = pkg_parts[: len(pkg_parts) - (node.level - 1)] if node.level > 1 else pkg_parts
                        base = ".".join([*up, base] if base else up)
                    targets = [(base, [a.name for a in node.names])]
                for mod, names in targets:
                    self._imports_seen.setdefault(modname, set()).add(mod)
                    if mod in WEB_MODULES or mod.split(".")[0] in WEB_MODULES:
                        rep.issues.append(Issue("desktop", "Design conformance",
                                                f"imports web framework/server '{mod}'; the game must be a "
                                                f"desktop (Tkinter) application, not a web application", rel, node.lineno))
                        continue
                    self._check_import(rel, node.lineno, mod, names, index, trees, rep)
                    if in_domain and (mod == f"{ROOT_PACKAGE}.ui" or mod.startswith(f"{ROOT_PACKAGE}.ui.")
                                      or (mod == ROOT_PACKAGE and names and "ui" in names)):
                        rep.issues.append(Issue("layering", "Design conformance",
                                                f"domain package '{in_domain}' imports the UI layer ({mod}); "
                                                f"domain code must not depend on Tkinter screens", rel, node.lineno))
            # dangerous calls / SQL built from strings
            if isinstance(node, ast.Call):
                name = _call_name(node.func)
                if name in FORBIDDEN_CALLS:
                    rep.issues.append(Issue("security", "Security", f"forbidden call {name}() in generated code",
                                            rel, node.lineno))
                if isinstance(node.func, ast.Attribute) and node.func.attr in SQL_METHODS and node.args:
                    q = node.args[0]
                    dynamic = isinstance(q, (ast.JoinedStr, ast.BinOp)) or (
                        isinstance(q, ast.Call) and isinstance(q.func, ast.Attribute) and q.func.attr == "format")
                    if dynamic:
                        rep.issues.append(Issue("security", "Security",
                                                "SQL text built with f-string/format/concatenation; use ? parameters",
                                                rel, node.lineno))
            # GUI event loop inside tests would hang the runner
            if rel.startswith("tests/") and isinstance(node, ast.Call) and _call_name(node.func).endswith("mainloop"):
                rep.issues.append(Issue("tests", "Reliability", "tests must never call mainloop()", rel, node.lineno))

    def _check_desktop_ui(self, rep: Report):
        ui_prefix = f"{ROOT_PACKAGE}.ui"
        ui_imports = set().union(*[v for k, v in self._imports_seen.items()
                                   if k == ui_prefix or k.startswith(ui_prefix + ".")] or [set()])
        if (self.root / ROOT_PACKAGE / "ui").is_dir() and not any(m == "tkinter" or m.startswith("tkinter.")
                                                                  for m in ui_imports):
            rep.issues.append(Issue("desktop", "Design conformance",
                                    f"no module in {ROOT_PACKAGE}/ui imports tkinter; the UI must be a Tkinter "
                                    f"desktop interface", f"{ROOT_PACKAGE}/ui"))
        main_imports = self._imports_seen.get("main", set())
        if (self.root / "main.py").is_file() and not any(m.startswith(ROOT_PACKAGE) for m in main_imports):
            rep.issues.append(Issue("desktop", "Design conformance",
                                    f"main.py does not import the {ROOT_PACKAGE} package, so it cannot start the game",
                                    "main.py"))

    def _check_import(self, rel, line, mod, names, index, trees, rep):
        if not mod:
            return
        top = mod.split(".")[0]
        if top in STDLIB:
            return
        local_tops = {m.split(".")[0] for m in index}
        if top not in local_tops:
            rep.issues.append(Issue("imports", "Hallucination",
                                    f"imports '{mod}', which is neither in the standard library nor in the "
                                    f"project (only the standard library is allowed)", rel, line))
            return
        if mod not in index:
            rep.issues.append(Issue("imports", "Hallucination",
                                    f"imports module '{mod}', which does not exist in the project", rel, line))
            return
        if names:
            target = index[mod]
            defined, star = _defined_names(trees[target]) if target in trees else (set(), True)
            if star:
                return
            for n in names:
                if n == "*" or n in defined or f"{mod}.{n}" in index:
                    continue
                rep.issues.append(Issue("imports", "Hallucination",
                                        f"'from {mod} import {n}': '{n}' is not defined in {self._rel(target)}",
                                        rel, line))

    def _check_docs(self, rep: Report):
        dec = self.root / "DECISIONS.md"
        if dec.is_file():
            text = dec.read_text(encoding="utf-8", errors="replace")
            missing = [c["id"] for c in self.arch.get("conflicts", []) if not re.search(rf"\b{c['id']}\b", text)]
            if missing:
                rep.issues.append(Issue("decisions", "Traceability & documentation",
                                        f"DECISIONS.md does not address conflict(s) {missing}", "DECISIONS.md"))
        tm = self.root / "traceability_matrix.csv"
        if tm.is_file():
            self._check_traceability(tm, rep)

    def _check_traceability(self, tm: Path, rep: Report):
        try:
            rows = list(csv.DictReader(io.StringIO(tm.read_text(encoding="utf-8-sig"))))
        except csv.Error as e:
            rep.issues.append(Issue("traceability", "Traceability & documentation", f"unreadable CSV: {e}",
                                    "traceability_matrix.csv"))
            return
        if not rows:
            rep.issues.append(Issue("traceability", "Traceability & documentation", "traceability matrix is empty",
                                    "traceability_matrix.csv"))
            return
        id_col = next((c for c in rows[0] if c and "requirement" in c.lower() and "id" in c.lower()), None) \
            or next((c for c in rows[0] if c and "id" in c.lower()), None)
        if not id_col:
            rep.issues.append(Issue("traceability", "Traceability & documentation",
                                    "no requirement id column", "traceability_matrix.csv"))
            return
        listed = {(r.get(id_col) or "").strip() for r in rows}
        expected = {r["id"] for r in self.arch.get("requirements", [])} | set(self.arch.get("requirement_ids_referenced", []))
        miss = sorted(expected - listed)
        if miss:
            rep.issues.append(Issue("traceability", "Traceability & documentation",
                                    f"requirements missing from the matrix: {miss}", "traceability_matrix.csv"))
        for r in rows:
            for col, val in r.items():
                if not col or not val or not any(k in col.lower() for k in ("file", "code", "test")):
                    continue
                for ref in re.split(r"[;|,\s]+", val):
                    ref = ref.strip()
                    if ref.endswith(".py") and not (self.root / ref).is_file():
                        rep.issues.append(Issue("traceability", "Traceability & documentation",
                                                f"{(r.get(id_col) or '?').strip()} points to a file that does not "
                                                f"exist: {ref}", "traceability_matrix.csv"))

    def _check_tests(self, rep: Report):
        if self.run_tests is None:
            return
        if not (self.root / "tests").is_dir():
            rep.issues.append(Issue("tests", "Functional", "no tests/ folder", "tests"))
            return
        res = self.run_tests()
        rep.tests_run, rep.tests_ok = res.get("tests_run", 0), bool(res.get("ok"))
        if res.get("fatal"):
            cat = "Reliability" if "TIMEOUT" in res["fatal"] else classify_test_problem(res["fatal"])
            rep.issues.append(Issue("tests", cat, "tests did not run: " + res["fatal"].strip()[-400:], "tests"))
            return
        for kind in ("failures", "errors"):
            for it in res.get(kind, []):
                last = it["trace"].strip().splitlines()[-1] if it["trace"].strip() else ""
                rep.issues.append(Issue("tests", classify_test_problem(it["trace"]),
                                        f"{kind[:-1]} in {it['test']}: {last[:200]}", "tests"))
        if rep.tests_run < MIN_TESTS:
            rep.issues.append(Issue("tests", "Functional",
                                    f"only {rep.tests_run} test(s); write at least {MIN_TESTS} covering the domain logic",
                                    "tests"))

    # bug report ---------------------------------------------------------------------------
    def write_bug_report(self) -> Path:
        seen: dict[str, dict] = {}
        for rep in self.history:
            for i in rep.issues:
                e = seen.setdefault(i.signature, {**asdict(i), "first_round": rep.round, "rounds": []})
                e["rounds"].append(rep.round)
        last = self.history[-1] if self.history else None
        final_sigs = {i.signature for i in last.issues} if last else set()
        entries = []
        for sig, e in seen.items():
            e["fixed"] = sig not in final_sigs
            entries.append(e)
        by_cat: dict[str, dict] = {}
        for e in entries:
            c = by_cat.setdefault(e["category"], {"found": 0, "fixed": 0})
            c["found"] += 1
            c["fixed"] += int(e["fixed"])
        data = {"taxonomy": "Gao et al., A Survey of Bugs in AI-Generated Code (arXiv:2512.05239) + project-level checks",
                "rounds": len(self.history),
                "final_passed": bool(last and last.passed),
                "final_tests_run": last.tests_run if last else 0,
                "by_category": by_cat,
                "issues": entries}
        self.log_dir.mkdir(parents=True, exist_ok=True)
        path = self.log_dir / "bug_report.json"
        path.write_text(json.dumps(data, indent=2), encoding="utf-8")
        return path
